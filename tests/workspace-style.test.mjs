assert(icon("🛠️x9")==="🛠️x","emoji with variation selector counts as one character");
assert(color("#AABBCC")==="#aabbcc","valid colour normalised to lower case");
for(const bad of ["red","#fff","javascript:1","#12345g",undefined,null,""]) assert(color(bad)==="#0060df","invalid colour rejected: "+bad);
assert(text("#ffd400")==="#1b1b1b","dark text on yellow");

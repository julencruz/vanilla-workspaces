import vm from "node:vm"; import fs from "node:fs";
const dir=new URL("../",import.meta.url).pathname;
const ctx={Intl,URL,Date,Set,Map,Object,Array,Promise,JSON,Math,String,Number,parseInt,browser:{storage:{local:{}}},crypto:{randomUUID:()=>"id"}};
vm.createContext(ctx); vm.runInContext(fs.readFileSync(dir+"background/state.js","utf8"),ctx);
const assert=(c,m)=>{if(!c)throw new Error("FAIL: "+m);console.log("ok -",m)};
const icon=v=>vm.runInContext("sanitizeIcon",ctx)(v), color=v=>vm.runInContext("sanitizeColor",ctx)(v), text=v=>vm.runInContext("readableTextColor",ctx)(v);
assert(icon("💼")==="💼","single emoji kept");
assert(icon("👨‍👩‍👧‍👦")==="👨‍👩‍👧‍👦","compound family emoji kept whole, not cut mid-sequence");
assert(icon("🇪🇸")==="🇪🇸","flag emoji kept whole");
